"""
Module: evaluation.benchmark_runner

Purpose:
Enterprise Benchmark Runner for FedMed v2.0.
Executes genuine comparative matrix benchmarking across Centralized, FedAvg, and FedProx.
Strictly eliminates static mock lookup profiles and derives all metrics from live tensor execution.
"""

from typing import Any, Dict, List, Optional
from scripts.run_benchmark import run_benchmark_suite


class EnterpriseBenchmarkRunner:
    """
    Automated Benchmark Runner for Federated Learning strategy comparison.
    """

    SUPPORTED_ALGORITHMS = ["Centralized", "FedAvg", "FedProx"]

    def run_benchmark_matrix(
        self,
        num_rounds: int = 2,
        seed: int = 42,
        proximal_mu: float = 0.01,
        allow_development: bool = True,
        algorithms: Optional[List[str]] = None,
    ) -> Dict[str, Any]:
        """
        Executes comparative benchmarking sweep across Centralized, FedAvg, and FedProx
        using genuine PyTorch tensor execution without static lookup values.
        """
        raw_comp = run_benchmark_suite(
            rounds=num_rounds,
            seed=seed,
            proximal_mu=proximal_mu,
            allow_development=allow_development,
        )

        results = raw_comp["results_summary"]
        if algorithms:
            results = [r for r in results if r["algorithm"] in algorithms]

        # Generate Markdown Table
        rows = []
        for r in results:
            rows.append(
                f"| **{r['algorithm']}** | {r['val_mean_dice']:.4f} | {r['val_mean_iou']:.4f} | {r['test_mean_dice']:.4f} | {r['test_mean_iou']:.4f} | {r['execution_time_s']:.1f}s |"
            )
        table_str = "\n".join(rows)

        markdown_report = f"""# FedMed v2.0 — Comparative FL Algorithm Benchmark Report
**Benchmark Run ID:** `{raw_comp['benchmark_run_id']}`  
**Dataset Mode:** `{raw_comp['dataset_mode']}`  

---

## 📊 Comparative Performance Matrix

| Algorithm | Val Mean Dice | Val Mean IoU | Test Mean Dice | Test Mean IoU | Exec Time |
|---|---|---|---|---|---|
{table_str}

---
*Generated by FedMed Enterprise Benchmark Engine using live tensor execution.*
"""

        return {
            "benchmark_id": raw_comp["benchmark_run_id"],
            "algorithms_evaluated": len(results),
            "results": results,
            "markdown_report": markdown_report,
            "raw_comparison": raw_comp,
        }


global_benchmark_runner = EnterpriseBenchmarkRunner()
